// ─── PDF REPORT GENERATION (real PDF, embeds actual images + results) ───────
function generatePdfReport(results, imgSrc, G) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const margin = 40;
  let y = 50;

  // Header
  doc.setFontSize(18);
  doc.setFont("helvetica", "bold");
  doc.text("NETRA AI — Clinical Screening Report", margin, y);
  y += 16;
  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(100);
  doc.text("Rural PHC Diabetic Retinopathy Screening · SIH 26038", margin, y);
  doc.text(new Date().toLocaleString(), pageW - margin, y, { align: "right" });
  y += 8;
  doc.setDrawColor(180);
  doc.line(margin, y, pageW - margin, y);
  y += 24;

  // Grade result box
  doc.setFillColor(245, 245, 245);
  doc.rect(margin, y, pageW - margin * 2, 60, "F");
  doc.setTextColor(20);
  doc.setFontSize(9);
  doc.setFont("helvetica", "bold");
  doc.text("AI GRADING RESULT", margin + 10, y + 16);
  doc.setFontSize(15);
  doc.text(`Grade ${results.grade}: ${G.name}`, margin + 10, y + 36);
  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.text(`Confidence: ${(results.confidence * 100).toFixed(1)}%   ·   Triage: ${G.urgency}`, margin + 10, y + 50);
  y += 80;

  // Images row (Original, Enhanced, Vessels, Grad-CAM)
  const imgs = [
    { label: "Original", src: imgSrc },
    { label: "CLAHE Enhanced", src: results.enhanced },
    { label: "Frangi Vessels", src: results.vessels },
    { label: "Grad-CAM", src: results.heatmap },
  ];
  const imgSize = (pageW - margin * 2 - 30) / 4;
  imgs.forEach((im, i) => {
    const x = margin + i * (imgSize + 10);
    try {
      doc.addImage(im.src, "JPEG", x, y, imgSize, imgSize);
    } catch (e) { /* skip if image fails to embed */ }
    doc.setFontSize(7);
    doc.setTextColor(80);
    doc.text(im.label, x + imgSize / 2, y + imgSize + 10, { align: "center" });
  });
  y += imgSize + 26;

  // Clinical recommendation
  doc.setFontSize(9);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(20);
  doc.text("CLINICAL RECOMMENDATION", margin, y);
  y += 14;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  const actionLines = doc.splitTextToSize(G.action, pageW - margin * 2);
  doc.text(actionLines, margin, y);
  y += actionLines.length * 12 + 16;

  // Quality metrics
  doc.setFont("helvetica", "bold");
  doc.text("IMAGE QUALITY METRICS", margin, y);
  y += 14;
  doc.setFont("helvetica", "normal");
  doc.text(`Quality: ${results.quality}/100     Sharpness: ${results.sharpness}     Entropy: ${results.entropy}`, margin, y);
  y += 24;

  // Probability distribution
  doc.setFont("helvetica", "bold");
  doc.text("GRADE PROBABILITY DISTRIBUTION", margin, y);
  y += 14;
  doc.setFont("helvetica", "normal");
  results.probs.forEach((p, i) => {
    doc.text(`Grade ${i} — ${GRADES[i].name}`, margin, y);
    doc.text(`${(p * 100).toFixed(1)}%`, pageW - margin, y, { align: "right" });
    y += 13;
  });
  y += 16;

  // Footer disclaimer
  doc.setDrawColor(180);
  doc.line(margin, y, pageW - margin, y);
  y += 16;
  doc.setFontSize(8);
  doc.setTextColor(120);
  const disclaimer = "AI screening decision support only — not a clinical diagnosis. Confirm with a qualified ophthalmologist. Generated by Netra AI (SIH 26038).";
  doc.text(doc.splitTextToSize(disclaimer, pageW - margin * 2), margin, y);

  doc.save(`netra_ai_report_grade${results.grade}.pdf`);
}

