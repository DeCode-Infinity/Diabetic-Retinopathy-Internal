  const [error,setError]=useState("");
  const [recapture,setRecapture]=useState(null);

  const fileRef=useRef(null);
  const timers=useRef([]);

  // Drives the phase-progress animation while the real API call is in flight.
  // The animation loops through phases; when the fetch resolves, we jump straight to results.
  const runRealPipeline = useCallback((file, dataUrl) => {
    timers.current.forEach(clearTimeout);
    timers.current = [];
    setImgSrc(dataUrl); setStage("processing"); setError("");
    setPhaseIdx(-1); setDone([]); setTab("original"); setResults(null);

    // step through phases visually every ~650ms, holding on the last phase
    // (not looping) once reached, so it never looks stuck-then-restarting
    let i = 0;
    const stepMs = 650;
    const stepper = setInterval(() => {
      const clampedIdx = Math.min(i, PHASES.length - 1);
      setPhaseIdx(clampedIdx);
      setDone(prev => {
        const next = [...prev];
        const prevIdx = i - 1;
        if (prevIdx >= 0 && prevIdx < PHASES.length - 1 && !next.includes(prevIdx)) next.push(prevIdx);
        return next;
      });
      if (i < PHASES.length - 1) i++;
    }, stepMs);
    timers.current.push(stepper);

    const formData = new FormData();
    formData.append("file", file);

    fetch(`${API_URL}/predict`, { method: "POST", body: formData })
      .then(async res => {
        if (res.status === 422) {
          const body = await res.json();
          clearInterval(stepper);
          setRecapture({ issues: body.detail?.issues || ["Image quality too low"], quality: body.detail?.quality });
          setStage("upload");
          return null;
        }
        if (!res.ok) throw new Error(`Server responded ${res.status}`);
        return res.json();
      })
      .then(data => {
        if (!data) return;
        clearInterval(stepper);
        setDone([0,1,2,3,4]);
        setPhaseIdx(4);
        setTimeout(() => {
          setResults(data);
          setStage("results");
        }, 350);
      })
      .catch(err => {
        clearInterval(stepper);
        setError(err.message || "Could not reach the model server.");
        setStage("apiError");
      });
  }, []);

